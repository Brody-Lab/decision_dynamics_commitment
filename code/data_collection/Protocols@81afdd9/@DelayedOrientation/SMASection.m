%% function make_perinic_stimulus_scheduled_wave

function [sma, plus_name, minus_name] = make_perinic_stimulus_scheduled_wave(sma, name, stim_type, ...
   flash_frequency, center1led, left1led, right1led)
     % Make a scheduled wave that will control the perinic stimuli
     switch stim_type
        case 'C LED on',
           sma = add_scheduled_wave(sma, 'name', name, ...
              'preamble', 0, 'sustain', 10, 'refraction', 0, 'loop', -1, ...
              'DOut', center1led);
           plus_name  = ['+' name];
           minus_name = ['-' name];
        case 'C LED flash',
           sma = add_scheduled_wave(sma, 'name', name, ...
              'preamble', 0, 'sustain', 0.5/flash_frequency, 'refraction', 0.5/flash_frequency, ...
              'loop', -1, 'DOut', center1led);
           plus_name  = ['+' name];
           minus_name = ['-' name];
        case 'C/S LEDs counterflash'
           sma = add_scheduled_wave(sma, 'name', [name '_1'], ...
              'preamble', 0.5/flash_frequency, 'sustain', 0.5/flash_frequency, 'refraction', 0, ...
              'loop', -1, 'DOut', center1led);
           sma = add_scheduled_wave(sma, 'name', [name '_2'], ...
              'preamble', 0, 'sustain', 0.5/flash_frequency, 'refraction', 0.5/flash_frequency, ...
              'loop', -1, 'DOut', left1led);
           sma = add_scheduled_wave(sma, 'name', [name '_3'], ...
              'preamble', 0, 'sustain', 0.5/flash_frequency, 'refraction', 0.5/flash_frequency, ...
              'loop', -1, 'DOut', right1led);           
           plus_name   = sprintf('+ %s_1 + %s_2 + %s_3', name, name, name);
           minus_name  = sprintf('- %s_1 - %s_2 - %s_3', name, name, name);
        case 'sound', 
           error('sound not yet implemented for %s', name);
           % sma = add_scheduled_wave(sma, 'name', 'prenic_stimulus', ...
           %   'preamble', 0, 'sustain', value(prenic_sound_dur), 'refraction', 0, 'loop', -1, ...
           %   'sound_trig', SoundManagerSection(obj, 'get_sound_id', 'prenic_sound'));
        case 'none',
           sma = add_scheduled_wave(sma, 'name', name, ...
              'preamble', 0, 'sustain', 0, 'refraction', 0);
           plus_name  = ['+' name];
           minus_name = ['-' name];
        otherwise
           error('Sorry, don''t recognize %s = "%s"\n', name, stim_type);
     end;

     return;
     